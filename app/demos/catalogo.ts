function familiaDe(rubro: string) {
  const normalizado = rubro.toLocaleLowerCase('es')
  return (
    FAMILIAS.find((f) => f.matches.length > 0 && f.matches.some((m) => normalizado.includes(m))) ??
    FAMILIAS[FAMILIAS.length - 1]
  ).title
}

/** Un demo tiene ruta si es de data.ts (ruta dinámica) o si tiene carpeta propia con page.tsx. */
const DINAMICOS = new Set(DEMOS.map((d) => d.slug))
function tieneRuta(slug: string) {
  return DINAMICOS.has(slug) || existsSync(join(process.cwd(), 'app', 'demos', slug, 'page.tsx'))
}

/** El sitio no usa guion largo en texto visible; algunos rubros y nombres del registro sí lo traen. */
const sinGuionLargo = (t: string) => t.replace(/\s*—\s*/g, ' · ')

let cache: DemoCatalogo[] | null = null

/** Todos los demos publicados, sin duplicados y solo los que tienen página, ordenados por nombre. */
export function catalogo(): DemoCatalogo[] {
  if (cache) return cache
  const porSlug = new Map<string, DemoCatalogo>()
  const agregar = (d: { slug: string; name: string; rubro: string; city: string }, creado: string) => {
    if (porSlug.has(d.slug)) return
    porSlug.set(d.slug, {
      slug: d.slug,
      nombre: sinGuionLargo(d.name),
      rubro: sinGuionLargo(d.rubro),
      ciudad: d.city,
      familia: familiaDe(d.rubro),
      creado: CREADOS[d.slug] ?? creado,
    })
  }
  BLITZ.forEach((d) => agregar(d, BLITZ_CREATED[d.slug] ?? ''))
  DEMOS.forEach((d) => agregar(d, d.created ?? ''))
  agregar(CABANAS_LA_QUEBRADA, CABANAS_LA_QUEBRADA.created)
  cache = [...porSlug.values()]
    .filter((d) => tieneRuta(d.slug))
    .sort((a, b) => a.nombre.localeCompare(b.nombre, 'es'))
  return cache
}

/** Familias en el orden del catálogo, con cuántos demos tiene cada una (sin las vacías). */
export function familias(): { titulo: string; total: number }[] {
  const lista = catalogo()
  return FAMILIAS.map((f) => ({ titulo: f.title, total: lista.filter((d) => d.familia === f.title).length })).filter(
    (f) => f.total > 0,
  )
}
