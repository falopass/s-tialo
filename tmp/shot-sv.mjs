import { chromium } from 'playwright'
const b = await chromium.connectOverCDP('http://localhost:29229')
const p = await b.contexts()[0].newPage()
await p.setViewportSize({ width: 390, height: 844 })
await p.goto('http://localhost:4800/demos/swissvet-talcahuano/', { waitUntil: 'load', timeout: 45000 }).catch(()=>{})
await p.waitForTimeout(2500)
await p.screenshot({ path: '/tmp/sv-hero.png' })
await p.evaluate(() => document.querySelector('#servicios')?.scrollIntoView())
await p.waitForTimeout(1600)
await p.screenshot({ path: '/tmp/sv-serv.png' })
await p.evaluate(() => document.querySelector('#resenas')?.scrollIntoView())
await p.waitForTimeout(1600)
await p.screenshot({ path: '/tmp/sv-rev.png' })
await p.close()
